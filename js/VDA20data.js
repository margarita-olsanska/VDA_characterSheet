export function getEffectiveRoadSins(roadKey, seen = new Set()){

	const road = roadTypes[roadKey]
	if(!road) return []

	if(!road.parentRoad) return road.sins || []

	if(seen.has(roadKey)) return []
	seen.add(roadKey)

	const overrides = road.overrides || {}

	return getEffectiveRoadSins(road.parentRoad, seen).map(row => {

		const override = overrides[String(row.value)]
		if(!override) return row

		return {
			value: row.value,
			sin: override.sin || row.sin,
			rationale: override.rationale || row.rationale
		}
	})
}

